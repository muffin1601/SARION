import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const sourceApp = path.join(root, "src", "app");

const marketingRoots = [
  "(marketing)",
  "links",
  "scorecard/report",
  "rss.xml",
  "api/contact",
  "api/leads",
];

const appRoots = [
  "(app)",
  "(auth)",
  "checkout",
  "p",
  "portal",
  "api/activity",
  "api/auth",
  "api/billing",
  "api/clients",
  "api/cron",
  "api/dev",
];

const routeFileNames = new Set([
  "page.tsx",
  "route.ts",
  "layout.tsx",
  "loading.tsx",
  "error.tsx",
  "not-found.tsx",
  "opengraph-image.tsx",
]);

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(absolute)));
    else files.push(absolute);
  }
  return files;
}

function belongsTo(relative, roots) {
  const normalized = relative.split(path.sep).join("/");
  return roots.some((candidate) =>
    normalized === candidate || normalized.startsWith(`${candidate}/`),
  );
}

async function generate(workspace, roots) {
  const appDirectory = path.join(root, "apps", workspace, "src", "app");
  await mkdir(appDirectory, { recursive: true });

  const files = await walk(sourceApp);
  for (const source of files) {
    if (!routeFileNames.has(path.basename(source))) continue;
    const relative = path.relative(sourceApp, source);
    if (!belongsTo(relative, roots)) continue;
    const target = path.join(appDirectory, relative);
    await mkdir(path.dirname(target), { recursive: true });
    const modulePath = `@/app/${relative
      .replaceAll(path.sep, "/")
      .replace(/\.(tsx|ts)$/, "")}`;
    const sourceText = await readFile(source, "utf8");
    const hasDefault = /export\s+default\s/.test(sourceText);
    const isMetadataImage = path.basename(source) === "opengraph-image.tsx";
    const isLayout = path.basename(source) === "layout.tsx";
    if (isMetadataImage || isLayout) {
      // Next's metadata loader requires literal config exports (runtime/size),
      // and route layouts must be direct modules rather than re-export wrappers.
      await writeFile(target, sourceText);
      if (isLayout) {
        const sourceCss = path.join(path.dirname(source), "marketing.css");
        try {
          const css = await readFile(sourceCss, "utf8");
          await writeFile(path.join(path.dirname(target), "marketing.css"), css);
        } catch {
          // Only the marketing route group has a colocated global stylesheet.
        }
      }
      continue;
    }
    const lines = [
      ...(sourceText.trimStart().startsWith('"use client"') ? ['"use client";', ""] : []),
      "// Generated by scripts/generate-workspace-routes.mjs. Do not edit directly.",
      ...(hasDefault ? [`export { default } from ${JSON.stringify(modulePath)};`] : []),
      `export * from ${JSON.stringify(modulePath)};`,
      "",
    ];
    await writeFile(target, lines.join("\n"));
  }
}

// Only generated route wrappers are cleaned. Hand-authored workspace shells
// (root layouts, robots, middleware, configs) live outside the selected roots.
for (const [workspace, roots] of [
  ["marketing", marketingRoots],
  ["app", appRoots],
]) {
  for (const selectedRoot of roots) {
    await rm(path.join(root, "apps", workspace, "src", "app", selectedRoot), {
      recursive: true,
      force: true,
    });
  }
  await generate(workspace, roots);
}

